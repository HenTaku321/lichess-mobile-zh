import 'dart:isolate';

import 'package:flutter/services.dart';
import 'package:flutter/widgets.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:lichess_mobile/src/intl.dart';
import 'package:lichess_mobile/src/model/practice/practice_structure.dart';
import 'package:lichess_mobile/src/model/practice/practice_translations.dart';
import 'package:lichess_mobile/src/model/settings/general_preferences.dart';
import 'package:lichess_mobile/src/utils/json.dart';

/// A provider for [PracticeRepository].
final practiceRepositoryProvider = Provider<PracticeRepository>(
  (Ref ref) => PracticeRepository(rootBundle),
  name: 'PracticeRepositoryProvider',
);

/// The practice content in the language the app is set to, loaded once and kept for the lifetime of
/// the app.
final practiceStructureProvider = FutureProvider<PracticeStructure>((ref) {
  final locale =
      ref.watch(generalPreferencesProvider.select((prefs) => prefs.locale)) ??
      getSystemLocale(WidgetsBinding.instance);
  return ref.read(practiceRepositoryProvider).getStructure(locale: locale);
}, name: 'PracticeStructureProvider');

/// The practice content, read from the asset embedded in the app.
///
/// Practice is fully offline: the content comes from `assets/practice.json`, generated by
/// `scripts/gen_practice.dart`.
class const PracticeRepository(final AssetBundle _bundle) {
  static const asset = 'assets/practice.json';

  /// The chapter prose overlays, by locale.
  ///
  /// Upstream has no translation below the study level, so chapter text is English in every
  /// language on lichess.org; the overlays are ours, generated by `scripts/gen-practice-zh.mjs`.
  /// The full locale is tried before the bare language, so a regional overlay wins over the
  /// generic one, and adding a language is adding an entry here and its asset to `pubspec.yaml`.
  static const translationsAssets = {'zh': 'assets/practice.zh.json'};

  /// Decodes and parses the asset in a background isolate, as it is too big to be done on the UI
  /// isolate without dropping frames on slow devices.
  ///
  /// Without a [locale] no overlay is applied and the chapter prose stays English.
  Future<PracticeStructure> getStructure({Locale? locale}) async {
    final translations = await _loadTranslations(locale);
    final bytes = await _bundle.load(asset);
    return await Isolate.run(
      () => PracticeStructure.fromJson(
        jsonUtf8Decoder.convert(Uint8List.sublistView(bytes))! as Map<String, dynamic>,
        translations: translations,
      ),
      debugName: 'Practice structure parsing',
    );
  }

  /// The chapter prose overlay for [locale], or null when no translation ships for it.
  Future<PracticeTranslations?> _loadTranslations(Locale? locale) async {
    if (locale == null) return null;
    final asset =
        translationsAssets[locale.toLanguageTag()] ?? translationsAssets[locale.languageCode];
    if (asset == null) return null;
    try {
      final bytes = await _bundle.load(asset);
      return PracticeTranslations.fromJson(
        jsonUtf8Decoder.convert(Uint8List.sublistView(bytes)) as Map<String, dynamic>?,
      );
    } on Exception {
      // Practice must not fail over its translations: a broken overlay reads as English.
      return null;
    }
  }
}
