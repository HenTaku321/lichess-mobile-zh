/// The Chinese overlay for the opening names lichess serves at `/training/openings`.
///
/// Those names are the ones the puzzle-by-opening list, the puzzle tab's preview tiles and the
/// puzzle screen's title are built from, and they are English in every language: lila has no
/// translation source for opening names at all — `translation/source/puzzle.xml` covers puzzle
/// themes only — so they read English on lichess.org too.
///
/// This overlay closes that gap. It is generated once, offline, by `scripts/gen-openings-zh.mjs`
/// and keyed by the English name rather than by opening key, which makes it content-addressed: a
/// renamed opening simply misses and falls back to English, keys changing is a non-event, and a
/// name shared by several families ("Closed", "Exchange Variation") is stored once.
///
/// The asset also carries a `keys` section, generated by composing the same Chinese names the way
/// the app composes them (`'${family}: ${child}'` in `flatOpeningsListProvider`). It is what lets
/// the offline saved-opening list, which is left with nothing but an opening key, show Chinese
/// too. See [ofKey].
class const PuzzleOpeningTranslations(
  final Map<String, String> _byEnglishName,
  final Map<String, String> _byKey,
) {
  /// The overlays that ship, by locale.
  ///
  /// The full locale is tried before the bare language, so a regional overlay wins over the generic
  /// one, and adding a language is adding an entry here and its asset to `pubspec.yaml`. Mirrors
  /// `PracticeRepository.translationsAssets`, which does the same for the practice prose.
  static const assets = {'zh': 'assets/openings.zh.json'};

  /// The asset that covers [locale], or null when none ships for it.
  static String? assetFor(Locale locale) =>
      assets[locale.toLanguageTag()] ?? assets[locale.languageCode];

  /// Parses an overlay asset, or returns null when there is nothing usable in it.
  ///
  /// Unreadable input is not an error: the app is meant to show the English names rather than
  /// fail, so anything that is not a string-to-string object yields null.
  static PuzzleOpeningTranslations? fromJson(Map<String, dynamic>? json) {
    if (json == null) return null;
    final byEnglishName = _stringMap(json['names']);
    if (byEnglishName.isEmpty) return null;
    return PuzzleOpeningTranslations(byEnglishName, _stringMap(json['keys']));
  }

  static Map<String, String> _stringMap(Object? json) {
    if (json is! Map) return const {};
    final map = <String, String>{};
    for (final entry in json.entries) {
      final value = entry.value;
      if (entry.key is String && value is String && value.trim().isNotEmpty) {
        map[entry.key as String] = value;
      }
    }
    return map;
  }

  /// The overlay for the English opening name [english], or null when it does not cover it.
  String? ofName(String? english) => english == null ? null : _byEnglishName[english];

  /// The overlay for an opening key, or null when the overlay does not cover it.
  ///
  /// Only the offline saved-opening list needs this: everywhere else the app has the name that
  /// came with the key. The value is the whole displayed name, family included.
  String? ofKey(String? key) => key == null ? null : _byKey[key];

  /// The same families with every name it knows replaced, and every one it does not left as it
  /// was. Keys are untouched: they are what the app asks lichess for.
  IList<PuzzleOpeningFamily> apply(IList<PuzzleOpeningFamily> families) => families
      .map(
        (family) => (
          key: family.key,
          name: ofName(family.name) ?? family.name,
          count: family.count,
          openings: family.openings
              .map(
                (opening) => (
                  key: opening.key,
                  name: ofName(opening.name) ?? opening.name,
                  count: opening.count,
                ),
              )
              .toIList(),
        ),
      )
      .toIList();
}

/// The opening-name overlay for the current locale, or null when none ships for it.
///
/// Kept alive with the app's other content rather than `autoDispose`: it is a 50 KB asset that is
/// read again every time the puzzle tab is rebuilt, and the overlay has no reason to be reloaded.
final puzzleOpeningTranslationsProvider = FutureProvider<PuzzleOpeningTranslations?>((Ref ref) {
  final locale =
      ref.watch(generalPreferencesProvider.select((prefs) => prefs.locale)) ??
      getSystemLocale(WidgetsBinding.instance);
  return _loadTranslations(locale);
}, name: 'PuzzleOpeningTranslationsProvider');

Future<PuzzleOpeningTranslations?> _loadTranslations(Locale locale) async {
  final asset = PuzzleOpeningTranslations.assetFor(locale);
  if (asset == null) return null;
  try {
    final bytes = await rootBundle.load(asset);
    return PuzzleOpeningTranslations.fromJson(
      jsonUtf8Decoder.convert(Uint8List.sublistView(bytes)) as Map<String, dynamic>?,
    );
  } on Exception {
    // The names must not fail over their translations: a broken overlay reads as English.
    return null;
  }
}
