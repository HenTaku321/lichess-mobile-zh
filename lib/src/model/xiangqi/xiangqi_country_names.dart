/// The reader's name for a country, from an ISO [code] or the server's [englishName].
///
/// The Chinese fork shows Chinese names. Other locales keep the English name the API sent,
/// because xiangqi.com does not localise this table at all.
String? xiangqiLocalizedCountryName(Locale locale, {String? code, String? englishName}) {
  if (code == null && englishName == null) return null;
  if (locale.languageCode != 'zh') {
    return englishName ?? (code == null ? null : _englishByCode[code.toUpperCase()]) ?? code;
  }
  final normalizedCode = (code ?? _codeByEnglishName[englishName] ?? _apiNameAliases[englishName])
      ?.toUpperCase();
  return normalizedCode == null
      ? (englishName ?? code)
      : _zhHansByCode[normalizedCode] ?? englishName ?? code;
}
